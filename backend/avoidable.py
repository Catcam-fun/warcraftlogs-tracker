"""Which boss damage a player could have avoided (owner's rules, 2026-10-23).

The list is generated by scripts/build_avoidable.py (avoidable_damage.py) and the owner's answers
(avoidable_overrides.py) win over it. Raid-wide damage (raid_wide_damage.RAID_WIDE, measured on
Mythic kills) is never avoidable. A DoT applied by an avoidable spell is listed under its own ID with
its source's rule, so its ticks count wherever the hit that applied it landed.
"""
from avoidable_damage import AVOIDABLE
from avoidable_overrides import OVERRIDES
from raid_wide_damage import RAID_WIDE

TANK_SPECS = frozenset({"Blood", "Vengeance", "Guardian", "Brewmaster", "Protection"})


def rule_for(ability_id):
    """The ability's entry ({"rule": ...}), or None when it isn't listed (not avoidable)."""
    if ability_id in RAID_WIDE:
        return {"rule": "never"}
    return OVERRIDES.get(ability_id) or AVOIDABLE.get(ability_id)


def judge_hit(hit, spec):
    """True when the hit was avoidable for this player, False when not, None when it can't be told
    (a tank-soak rule with no spec for the pull). `spec`: the spec they played in that pull."""
    entry = rule_for(hit.get("abilityGameID"))
    rule = entry and entry["rule"]
    if rule == "always":
        return True
    if rule == "non_tank":
        return None if not spec else spec not in TANK_SPECS
    return False
